#!/usr/bin/env python3
"""Music for a film from a music model, cut to the film's grid.

Slate's own scorer writes notes and plays them on General MIDI samples. However well arranged, that
sounds like MIDI next to a produced launch film. So the music for a finished film comes from a real
music source: a track someone supplies, or a track generated by Google's Lyria through the Gemini API.
This tool does the second, then fits the result to the film the same way a supplied track is fitted.

  python3 tools/music.py prompt   films/<name>             print the brief it would send, and do nothing else
  python3 tools/music.py generate films/<name> [--takes 3] [--model lyria-3.5] [--extra "..."]
  python3 tools/music.py fit      films/<name> music/take-2.mp3

generate writes films/<name>/music/take-N.mp3 with the brief beside it (take-N.json), then fits the
first take. fit writes films/<name>/music/track.wav and music/track.json: the take stretched to the
film's tempo (when it is within 8%), with its first downbeat on the film's beat 0, trimmed to the film
and faded after the last cue. A film uses it with F.music({track: 'music/track.wav'}); the scorer then
mixes the film's foley over it and masters the mix as usual.

The brief is written from the film itself: its notes (idea, form, sound), tempo, key, length, and a
timed outline from its scenes, energy arc and resolve cue, so the music follows the cut. A few style
frames from the latest render go with it, so the model sees the look. Read the brief before spending a
generation: if it doesn't describe the film you'd score, fix the notes, not the prompt.

Needs GEMINI_API_KEY. Generated audio carries Google's SynthID watermark. Listen to every take; the
measurements below catch broken takes, not boring ones.
"""
import argparse
import base64
import glob
import json
import os
import subprocess
import sys
for _s in (sys.stdout, sys.stderr):  # ▸ and ✓ on a cp1252 console
    getattr(_s, 'reconfigure', lambda **k: None)(encoding='utf-8', errors='replace')
import urllib.error
import urllib.request

API = os.environ.get('GEMINI_API_BASE', 'https://generativelanguage.googleapis.com/v1beta')
SR = 48000

FORM_MUSIC = {
    'take': 'one steady, unhurried idea that never builds to a drop',
    'call': 'a groove in one gear with a clear pocket; it neither builds nor stops',
    'settle': 'starts fuller and thins out, ending on a single instrument',
    'reveal': 'a slow swell with little rhythm that opens up at the reveal',
    'loop': 'a repeating figure whose end flows back into its start',
    'trailer': 'builds in layers, cuts to near silence for a breath, then lands one big hit',
}


def mmss(t):
    t = max(0.0, t)
    return f'{int(t // 60)}:{t % 60:05.2f}'.replace('.00', '')


def load_manifest(film):
    p = os.path.join(film, 'build', 'manifest.json')
    if not os.path.exists(p):
        sys.exit(f'no {p}: run `node engine/render.mjs {film} --audit` first, it writes the manifest')
    return json.load(open(p, encoding='utf-8'))


def outline(man):
    """A timed outline of the film for the model: sections from scene boundaries, with their energy."""
    arc = (man.get('music') or {}).get('arc') or [[0, 0.5], [man['duration'], 0.5]]

    def energy(t):
        for (t0, e0), (t1, e1) in zip(arc, arc[1:]):
            if t0 <= t <= t1:
                return e0 + (e1 - e0) * ((t - t0) / (t1 - t0) if t1 > t0 else 0)
        return arc[-1][1]

    resolve = next((e['t'] for e in man['events'] if e['type'] == 'resolve'), None)
    cuts = sorted({round(s['start'], 2) for s in man['scenes'] if s['start'] < man['duration']} | {0.0})
    if resolve is not None:
        cuts = sorted(set([c for c in cuts if c < resolve - 0.5] + [round(resolve, 2)]))
    bounds = cuts + [man['duration']]
    words = {0.25: 'very sparse, almost still', 0.45: 'light and open', 0.6: 'settled in the groove, steady',
             0.75: 'full, warm, moving', 1.01: 'at its fullest'}
    lines = []
    for a, b in zip(bounds, bounds[1:]):
        if b - a < 0.5:
            continue
        here = [s for s in man['scenes'] if s['start'] <= a + 1e-3 < s['end']]
        kind = {'type': 'words on screen', 'product': 'the product in use', 'logo': 'the name', 'world': 'image'}
        what = ', '.join(sorted({kind.get(s['kind'], s['kind']) for s in here})) or 'image'
        e = energy((a + b) / 2)
        feel = next(v for k, v in words.items() if e < k)
        if resolve is not None and a >= resolve - 1e-3:
            feel = 'the music resolves on a final chord at the start of this section and lets it ring out to silence; nothing new enters'
        lines.append(f'[{mmss(a)} - {mmss(b)}] {what}: {feel}.')
    return lines, resolve


def brief(man, extra=''):
    notes, m = man.get('notes') or {}, man.get('music') or {}
    form = (notes.get('form') or '').lower()
    shape = next((v for k, v in FORM_MUSIC.items() if form.startswith(('the ' + k, k, 'a ' + k))), None)
    lines, resolve = outline(man)
    parts = [
        f"Instrumental music for a {man['duration']:.0f}-second product film. No vocals, no lyrics, no spoken words.",
        f"Exactly {man['bpm']:g} BPM in 4/4{' in ' + m['key'] if m.get('key') else ''}, starting on a downbeat at 0:00, "
        f"and exactly {man['duration']:.1f} seconds long.",
    ]
    if notes.get('sound'):
        parts.append('The sound: ' + notes['sound'])
    if shape:
        parts.append('Its shape: ' + shape + '.')
    if notes.get('idea'):
        parts.append('What the film is about: ' + notes['idea'])
    parts.append('Produced and mixed like music for a modern tech launch film: recorded instruments, a real low end, '
                 'warm and clean, plenty of space, nothing cheesy or stock-sounding, no risers into a drop unless asked.')
    parts.append('Timeline:\n' + '\n'.join(lines))
    if extra:
        parts.append(extra)
    return '\n\n'.join(parts)


def style_frames(film, n=4):
    """A few frames from the latest render (or its stills), as JPEG bytes."""
    name = os.path.basename(os.path.normpath(film))
    root = os.path.dirname(os.path.dirname(os.path.abspath(film)))
    video = os.path.join(root, 'out', f'{name}.mp4')
    frames = []
    if os.path.exists(video):
        dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', video],
                                   capture_output=True, text=True).stdout or 0)
        for k in range(n):
            t = dur * (k + 0.5) / n
            jpg = subprocess.run(['ffmpeg', '-v', 'error', '-ss', f'{t:.2f}', '-i', video, '-frames:v', '1', '-vf', 'scale=960:-2',
                                  '-q:v', '4', '-f', 'image2', '-c:v', 'mjpeg', '-'], capture_output=True).stdout
            if jpg:
                frames.append(jpg)
    else:
        for f in sorted(glob.glob(os.path.join(film, 'build', 'stills', '*.png')))[:n]:
            frames.append(subprocess.run(['ffmpeg', '-v', 'error', '-i', f, '-vf', 'scale=960:-2', '-q:v', '4', '-f', 'image2',
                                          '-c:v', 'mjpeg', '-'], capture_output=True).stdout)
    return [f for f in frames if f]


def request(model, text, images, key):
    blocks = [{'type': 'text', 'text': text}] + [
        {'type': 'image', 'mime_type': 'image/jpeg', 'data': base64.b64encode(im).decode()} for im in images]
    body = json.dumps({'model': model, 'input': blocks}).encode()
    req = urllib.request.Request(f'{API}/interactions', data=body, method='POST',
                                 headers={'Content-Type': 'application/json', 'x-goog-api-key': key})
    try:
        with urllib.request.urlopen(req, timeout=600) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        sys.exit(f'{model}: HTTP {e.code}: {e.read().decode(errors="replace")[:800]}')


def audio_of(resp):
    """The last audio block of an interaction: in steps[].content[] (current) or outputs[] (older previews)."""
    blocks = []
    for step in resp.get('steps') or []:
        blocks += step.get('content') or []
    blocks += resp.get('outputs') or []
    audio = [b for b in blocks if b.get('type') == 'audio' and b.get('data')]
    if not audio:
        return None, None
    b = audio[-1]
    return base64.b64decode(b['data']), b.get('mime_type') or 'audio/mpeg'


def decode(path, sr=SR):
    import numpy as np
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 'f32le', '-ac', '2', '-ar', str(sr), '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).reshape(-1, 2).astype(np.float64)


def grid(path):
    """Tempo and first downbeat of a track (librosa), the same way tools/beatgrid.py finds them."""
    import numpy as np
    import librosa
    y, sr = librosa.load(path, sr=22050, mono=True)
    tempo, frames = librosa.beat.beat_track(y=y, sr=sr)
    tempo = float(np.atleast_1d(tempo)[0])
    beats = librosa.frames_to_time(frames, sr=sr)
    s = librosa.onset.onset_strength(y=y, sr=sr)[frames] if len(frames) else np.zeros(1)
    phase = int(np.argmax([s[p::4].mean() if len(s[p::4]) else 0 for p in range(4)])) if len(s) >= 8 else 0
    return tempo, (float(beats[phase]) if len(beats) > phase else 0.0), beats


def fit(film, take, man=None):
    """Stretch a take to the film's tempo, put its downbeat on beat 0, trim, fade after the last cue."""
    import numpy as np
    from scipy.io import wavfile
    man = man or load_manifest(film)
    src = take if os.path.isabs(take) else os.path.join(film, take)
    tempo, offset, beats = grid(src)
    bpm = float(man['bpm'])
    # librosa sometimes hears half or double time
    for k in (0.5, 2.0):
        if abs(tempo * k - bpm) < abs(tempo - bpm):
            tempo *= k
    ratio = bpm / tempo if tempo else 1.0
    stretched = src
    if abs(ratio - 1) > 0.004 and abs(ratio - 1) < 0.08:
        stretched = os.path.join(film, 'music', '.stretched.wav')
        has_rb = 'rubberband' in subprocess.run(['ffmpeg', '-hide_banner', '-filters'], capture_output=True, text=True).stdout
        af = f'rubberband=tempo={ratio:.5f}' if has_rb else f'atempo={ratio:.5f}'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-af', af, '-ar', str(SR), stretched], check=True)
        offset /= ratio
    elif abs(ratio - 1) >= 0.08:
        print(f'▸ the take is at {tempo:.1f} BPM, too far from the film\'s {bpm:g} to stretch cleanly; '
              f'kept as is. Consider film({{bpm: {tempo:.1f}}}).')
        ratio = 1.0
    x = decode(stretched)
    # start a bar early if the downbeat comes late, so beat 0 of the film is a downbeat of the music
    bar = 4 * 60 / bpm
    start = offset - bar * int(offset // bar)
    n = int(round(man['duration'] * SR))
    a = int(round(start * SR))
    out = np.zeros((n, 2))
    seg = x[a:a + n]
    out[:len(seg)] = seg
    # the tail: let it ring from the resolve, then a gentle fade into the last frame
    resolve = next((e['t'] for e in man['events'] if e['type'] == 'resolve'), None)
    fade = min(2.5, max(0.8, man['duration'] - (resolve or man['duration'] - 1.5)))
    f = int(fade * SR)
    out[-f:] *= np.linspace(1, 0, f)[:, None] ** 2
    head = int(0.004 * SR)
    out[:head] *= np.linspace(0, 1, head)[:, None]
    os.makedirs(os.path.join(film, 'music'), exist_ok=True)
    dst = os.path.join(film, 'music', 'track.wav')
    peak = np.max(np.abs(out)) or 1
    wavfile.write(dst, SR, (out / max(1, peak / 0.98) * 32767).astype(np.int16))
    if stretched != src:
        os.remove(stretched)
    meta = {'source': os.path.relpath(src, film), 'tempo': round(tempo, 2), 'bpm': bpm, 'stretch': round(ratio, 5),
            'downbeat': round(start, 3), 'duration': man['duration']}
    json.dump(meta, open(os.path.join(film, 'music', 'track.json'), 'w', encoding='utf-8'), indent=2)
    print(f"▸ fitted {meta['source']}: {tempo:.1f} → {bpm:g} BPM (×{ratio:.3f}), downbeat at {start:.3f}s -> music/track.wav")
    print("▸ use it with F.music({track: 'music/track.wav'}) and render")
    return dst


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd', choices=['prompt', 'generate', 'fit'])
    ap.add_argument('film')
    ap.add_argument('take', nargs='?', help='fit: the take to fit, relative to the film')
    ap.add_argument('--model', default='lyria-3.5', help='lyria-3.5 (follows a timed outline) or lyria-3-clip-preview (30s clips)')
    ap.add_argument('--takes', type=int, default=3)
    ap.add_argument('--extra', default='', help='anything to add to the brief')
    ap.add_argument('--no-frames', action='store_true', help="don't send style frames")
    a = ap.parse_args()
    film = os.path.normpath(a.film)
    if a.cmd == 'fit':
        if not a.take:
            sys.exit('fit needs a take: music.py fit films/<name> music/take-1.mp3')
        fit(film, a.take)
        return
    man = load_manifest(film)
    text = brief(man, a.extra)
    if a.cmd == 'prompt':
        print(text)
        return
    key = os.environ.get('GEMINI_API_KEY')
    if not key:
        sys.exit('generate needs GEMINI_API_KEY in the environment (a Gemini API key with access to Lyria)')
    images = [] if a.no_frames else style_frames(film)
    os.makedirs(os.path.join(film, 'music'), exist_ok=True)
    first = None
    existing = len(glob.glob(os.path.join(film, 'music', 'take-*.json')))
    for k in range(existing + 1, existing + a.takes + 1):
        print(f'▸ {a.model}: take {k} ({len(images)} style frames)…')
        data, mime = audio_of(request(a.model, text, images, key))
        if not data:
            print('  no audio in the response (blocked by a filter?); try again or adjust --extra')
            continue
        ext = {'audio/wav': 'wav', 'audio/x-wav': 'wav', 'audio/mpeg': 'mp3', 'audio/mp3': 'mp3', 'audio/ogg': 'ogg'}.get(mime, 'mp3')
        path = os.path.join(film, 'music', f'take-{k}.{ext}')
        open(path, 'wb').write(data)
        json.dump({'model': a.model, 'brief': text, 'frames': len(images), 'mime': mime}, open(path.rsplit('.', 1)[0] + '.json', 'w', encoding='utf-8'), indent=2)
        tempo, offset, _ = grid(path)
        print(f'  -> {os.path.relpath(path, film)}: {tempo:.1f} BPM, downbeat at {offset:.2f}s')
        first = first or os.path.relpath(path, film)
    if first:
        fit(film, first, man)
        print('▸ listen to every take; fit another with: python3 tools/music.py fit', film, 'music/take-N.mp3')


if __name__ == '__main__':
    main()
